func (c *ProfileConfig) ToYAML() (string, error) {
	tmpl := `# SDP Profile Configuration
# Generated by: sdp up --profile {{.ProfileName}}
# Version: {{.Version}}

profile:
  name: {{.ProfileName}}
  version: {{.Version}}

adapters:
{{- range .Adapters}}
  - system: {{.System}}
    endpoint: {{.Endpoint}}
    contract: {{.ContractPath}}
    version: {{.Version}}
    enabled: {{.Enabled}}
{{- end}}

guard:
  scopes:
{{- range .GuardScopes}}
    - name: {{.Name}}
      path: {{.Path}}
      description: {{.Description}}
      evidence_path: {{.EvidencePath}}
      enabled: {{.Enabled}}
{{- end}}

paths:
  evidence: {{.EvidencePath}}
  checkpoints: {{.CheckpointsDir}}
  findings: {{.FindingsDir}}
  sessions: {{.SessionsDir}}
  traces: {{.TracesDir}}
`
	t, err := template.New("config").Parse(tmpl)
	if err != nil {
		return "", fmt.Errorf("parse template: %w", err)
	}

	var buf strings.Builder
	if err := t.Execute(&buf, c); err != nil {
		return "", fmt.Errorf("execute template: %w", err)
	}

	return buf.String(), nil
}

