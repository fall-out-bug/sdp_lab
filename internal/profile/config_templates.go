func (c *ProfileConfig) GenerateConfigs(outputDir string, dryRun bool) error {
	configs := []struct {
		name    string
		content func() (string, error)
	}{
		{"config.yaml", c.ToYAML},
		{"adapters.yaml", c.ToAdaptersYAML},
		{"guard.yaml", c.ToGuardYAML},
	}

	for _, cfg := range configs {
		content, err := cfg.content()
		if err != nil {
			return fmt.Errorf("generate %s: %w", cfg.name, err)
		}

		path := filepath.Join(outputDir, cfg.name)
		if dryRun {
			fmt.Printf("  [DRY-RUN] Would create: %s (%d bytes)\n", path, len(content))
			continue
		}

		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return fmt.Errorf("create parent dir for %s: %w", path, err)
		}

		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}

		fmt.Printf("  ✓ %s\n", cfg.name)
	}

	return nil
}

type ConfigValidator struct {
	config *ProfileConfig
}

func NewConfigValidator(config *ProfileConfig) *ConfigValidator {
	return &ConfigValidator{config: config}
}

func (v *ConfigValidator) Validate() []ConfigValidationError {
	var errors []ConfigValidationError

	for _, adapter := range v.config.Adapters {
		if adapter.Enabled {
			if adapter.Endpoint == "" {
				errors = append(errors, ConfigValidationError{
					Field:   fmt.Sprintf("adapters.%s.endpoint", adapter.System),
					Message: "endpoint is required for enabled adapter",
				})
			}
			if adapter.ContractPath == "" {
				errors = append(errors, ConfigValidationError{
					Field:   fmt.Sprintf("adapters.%s.contract", adapter.System),
					Message: "contract path is required for enabled adapter",
				})
			}
			if adapter.Version == "" {
				errors = append(errors, ConfigValidationError{
					Field:   fmt.Sprintf("adapters.%s.version", adapter.System),
					Message: "version is required for enabled adapter",
				})
			}
		}
	}

	for _, scope := range v.config.GuardScopes {
		if scope.Enabled {
			if scope.Path == "" {
				errors = append(errors, ConfigValidationError{
					Field:   fmt.Sprintf("guard.scopes.%s.path", scope.Name),
					Message: "path is required for enabled scope",
				})
			}
			if scope.EvidencePath == "" {
				errors = append(errors, ConfigValidationError{
					Field:   fmt.Sprintf("guard.scopes.%s.evidence_path", scope.Name),
					Message: "evidence path is required for enabled scope",
				})
			}
		}
	}

	if v.config.EvidencePath == "" {
		errors = append(errors, ConfigValidationError{
			Field:   "paths.evidence",
			Message: "evidence path is required",
		})
	}

	return errors
}

type ConfigValidationError struct {
	Field   string
	Message string
}

func (e ConfigValidationError) Error() string {
	return fmt.Sprintf("%s: %s", e.Field, e.Message)
}

func ValidateConfigLint(configPath string) error {
	content, err := os.ReadFile(configPath)
	if err != nil {
		return fmt.Errorf("read config: %w", err)
	}

	requiredFields := []string{
		"profile:",
		"adapters:",
		"guard:",
		"paths:",
	}

	var missing []string
	for _, field := range requiredFields {
		if !strings.Contains(string(content), field) {
			missing = append(missing, field)
		}
	}

	if len(missing) > 0 {
		return fmt.Errorf("missing required fields: %s", strings.Join(missing, ", "))
	}

	return nil
}
