func TestBuildAgentNotes(t *testing.T) {
	ds := DataSourceInfo{
		Scout: &ScoutData{PrimaryLanguage: "Go", HasCI: true, CISystem: "github"},
	}
	cmds := BuildCommands{Build: "go build ./...", Test: "go test ./...", Lint: "golangci-lint run"}

	notes := buildAgentNotes(ds, cmds)
	assert.NotEmpty(t, notes)

	// Should have Claude, Codex, and All Agents notes.
	var foundClaude, foundCodex, foundAll bool
	for _, n := range notes {
		switch n.Agent {
		case "Claude Code":
			foundClaude = true
		case "Codex CLI":
			foundCodex = true
		case "All Agents":
			foundAll = true
		}
	}
	assert.True(t, foundClaude)
	assert.True(t, foundCodex)
	assert.True(t, foundAll)
}

