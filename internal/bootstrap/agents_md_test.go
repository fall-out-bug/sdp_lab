// --- Integration tests via Planner ---

func TestPlanner_Execute_GeneratesAgentsMD(t *testing.T) {
	dir := setupRepoWithScout(t)

	planner := NewPlanner(BootstrapConfig{RepoPath: dir, NoVerify: true})
	report, err := planner.Execute()
	require.NoError(t, err)

	agentsPath := filepath.Join(dir, "AGENTS.md")
	assert.FileExists(t, agentsPath)

	content, err := os.ReadFile(agentsPath)
	require.NoError(t, err)

	assert.Contains(t, string(content), "<!-- generated by sdp bootstrap: Available Agents -->")
	assert.Contains(t, string(content), "## Available Agents")
	assert.Contains(t, string(content), "Claude Code")

	var found bool
	for _, a := range report.Artifacts {
		if a.Type == "agents_md" {
			found = true
			assert.Equal(t, "ok", a.Status)
		}
	}
	assert.True(t, found)
}

func TestPlanner_Execute_ForceMerge_AgentsMD(t *testing.T) {
	dir := setupRepoWithScout(t)
	existing := "# My Agents\n\nMy custom intro.\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "AGENTS.md"), []byte(existing), 0o644))

	planner := NewPlanner(BootstrapConfig{RepoPath: dir, Force: true, NoVerify: true})
	report, err := planner.Execute()
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(dir, "AGENTS.md"))
	require.NoError(t, err)

	assert.Contains(t, string(content), "My custom intro.")
	assert.Contains(t, string(content), "<!-- generated by sdp bootstrap:")

	var found bool
	for _, a := range report.Artifacts {
		if a.Type == "agents_md" && a.Action == "merge" {
			found = true
			assert.Equal(t, "ok", a.Status)
		}
	}
	assert.True(t, found)
}

