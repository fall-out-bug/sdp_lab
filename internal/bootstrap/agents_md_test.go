func TestMergeAgentsMD_FreshMerge(t *testing.T) {
	dir := t.TempDir()
	existing := `# My Custom Agents Config

## Custom Agent Rules

My custom rules here.

## My Workflow

Custom workflow details.
`
	ds := DataSourceInfo{
		Scout: &ScoutData{PrimaryLanguage: "Go", BuildSystem: "go"},
	}
	cmds := BuildCommands{Build: "go build ./...", Test: "go test ./...", Lint: "golangci-lint run"}

	result, err := MergeAgentsMD(existing, dir, ds, cmds)
	require.NoError(t, err)

	// User content must be preserved.
	assert.Contains(t, result, "My Custom Agents Config")
	assert.Contains(t, result, "## Custom Agent Rules")
	assert.Contains(t, result, "My custom rules here.")
	assert.Contains(t, result, "## My Workflow")
	assert.Contains(t, result, "Custom workflow details.")

	// Generated sections should be added.
	assert.Contains(t, result, "<!-- generated by sdp bootstrap:")
}

