// --- Fresh generation tests ---

func TestGenerateAgentsMD_Fresh(t *testing.T) {
	dir := t.TempDir()
	ds := DataSourceInfo{
		Scout: &ScoutData{
			PrimaryLanguage: "Go",
			BuildSystem:     "go",
		},
	}
	cmds := BuildCommands{
		Build: "go build ./...",
		Test:  "go test ./...",
		Lint:  "golangci-lint run",
	}

	result, err := GenerateAgentsMD(dir, ds, cmds)
	require.NoError(t, err)

	// Verify structure.
	assert.Contains(t, result, "# Agent Coordination for "+filepath.Base(dir))
	assert.Contains(t, result, "## Available Agents")
	assert.Contains(t, result, "## Shared Conventions")
	assert.Contains(t, result, "## Agent-Specific Notes")

	// Verify default agents.
	assert.Contains(t, result, "Claude Code")
	assert.Contains(t, result, "Codex CLI")
	assert.Contains(t, result, "Cursor")

	// Verify generated markers (named markers).
	assert.Contains(t, result, "<!-- generated by sdp bootstrap: Available Agents -->")
	assert.Contains(t, result, "<!-- end generated by sdp bootstrap -->")

	// Verify shared conventions.
	assert.Contains(t, result, "Conventional commits")
	assert.Contains(t, result, "tests before committing")
}

