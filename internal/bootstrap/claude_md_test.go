// --- Integration tests via Planner ---

func TestPlanner_Execute_GeneratesClaudeMD(t *testing.T) {
	dir := setupRepoWithScout(t)

	planner := NewPlanner(BootstrapConfig{RepoPath: dir, NoVerify: true})
	report, err := planner.Execute()
	require.NoError(t, err)

	// Verify CLAUDE.md was created.
	claudePath := filepath.Join(dir, "CLAUDE.md")
	assert.FileExists(t, claudePath)

	content, err := os.ReadFile(claudePath)
	require.NoError(t, err)

	// Should have generated markers (named markers).
	assert.Contains(t, string(content), "<!-- generated by sdp bootstrap: Tech Stack -->")
	assert.Contains(t, string(content), "## Tech Stack")
	assert.Contains(t, string(content), "## Architecture")

	// Find the claude_md artifact in report.
	var found bool
	for _, a := range report.Artifacts {
		if a.Type == "claude_md" {
			found = true
			assert.Equal(t, "ok", a.Status)
		}
	}
	assert.True(t, found)
}

func TestPlanner_Execute_ForceMerge_ClaudeMD(t *testing.T) {
	dir := setupRepoWithScout(t)
	existing := "# my-project\n\nMy custom intro.\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "CLAUDE.md"), []byte(existing), 0o644))

	planner := NewPlanner(BootstrapConfig{RepoPath: dir, Force: true, NoVerify: true})
	report, err := planner.Execute()
	require.NoError(t, err)

	content, err := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	require.NoError(t, err)

	// User content must survive.
	assert.Contains(t, string(content), "My custom intro.")

	// Generated content should be added.
	assert.Contains(t, string(content), "<!-- generated by sdp bootstrap:")

	// Report should show merge action for claude_md.
	var found bool
	for _, a := range report.Artifacts {
		if a.Type == "claude_md" && a.Action == "merge" {
			found = true
			assert.Equal(t, "ok", a.Status)
		}
	}
	assert.True(t, found)
}

