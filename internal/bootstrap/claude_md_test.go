func TestGenerateClaudeMD_Fresh_GoProject(t *testing.T) {
	dir := t.TempDir()
	ds := DataSourceInfo{
		Scout: &ScoutData{
			PrimaryLanguage: "Go",
			BuildSystem:     "go",
			HasTests:        true,
			TestRatio:       0.5,
			CISystem:        "github",
		},
	}
	cmds := BuildCommands{
		Build: "go build ./...",
		Test:  "go test ./...",
		Lint:  "golangci-lint run",
	}

	result, err := GenerateClaudeMD(dir, ds, cmds)
	require.NoError(t, err)

	// Verify structure.
	assert.Contains(t, result, "# "+filepath.Base(dir))
	assert.Contains(t, result, "## Tech Stack")
	assert.Contains(t, result, "## Architecture")
	assert.Contains(t, result, "## Conventions")
	assert.Contains(t, result, "## Commands")
	assert.Contains(t, result, "## What NOT to Do")

	// Verify language-specific content.
	assert.Contains(t, result, "Go")
	assert.Contains(t, result, "go build")
	assert.Contains(t, result, "go test")
	assert.Contains(t, result, "golangci-lint run")

	// Verify generated markers (named markers).
	assert.Contains(t, result, "<!-- generated by sdp bootstrap: Tech Stack -->")
	assert.Contains(t, result, "<!-- end generated by sdp bootstrap -->")
}

